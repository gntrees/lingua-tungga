//! URL imports, lockfile, cache, and vendoring for Lingua Tungga.
//!
//! Resolution rules:
//! - A locked URL is served from `vendor/` or the object cache when possible.
//! - Otherwise the pinned (commit) URL is fetched and verified against the lock.
//! - Unlocked URLs are fetched, hashed, and (for GitHub) pinned to a commit.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use lt_hir::{RemoteResolver, ResolvedRemote};
use sha2::{Digest, Sha256};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// Use `lt.lock`; only fetch what is missing.
    Locked,
    /// Re-resolve every URL and rewrite the lock.
    Update,
}

#[derive(Debug, Clone, Default)]
pub struct Package {
    pub url: String,
    pub canonical: String,
    pub commit: Option<String>,
    pub sha256: String,
}

#[derive(Debug, Clone, Default)]
pub struct Lockfile {
    pub packages: BTreeMap<String, Package>,
}

impl Lockfile {
    pub fn load(path: &Path) -> Result<Self, String> {
        let Ok(text) = std::fs::read_to_string(path) else {
            return Ok(Self::default());
        };
        Self::parse(&text)
    }

    pub fn parse(text: &str) -> Result<Self, String> {
        let mut packages = BTreeMap::new();
        let mut current: Option<Package> = None;
        for (number, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if line == "[[package]]" {
                if let Some(package) = current.take() {
                    if package.url.is_empty() {
                        return Err(format!("line {}: package without a url", number + 1));
                    }
                    packages.insert(package.url.clone(), package);
                }
                current = Some(Package::default());
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                return Err(format!("line {}: expected `key = \"value\"`", number + 1));
            };
            let value = value.trim();
            let value = value
                .strip_prefix('"')
                .and_then(|rest| rest.strip_suffix('"'))
                .ok_or_else(|| format!("line {}: expected a quoted value", number + 1))?;
            let Some(package) = current.as_mut() else {
                return Err(format!("line {}: key outside a [[package]]", number + 1));
            };
            match key.trim() {
                "url" => package.url = value.to_string(),
                "canonical" => package.canonical = value.to_string(),
                "commit" => package.commit = Some(value.to_string()),
                "sha256" => package.sha256 = value.to_string(),
                other => return Err(format!("line {}: unknown key `{other}`", number + 1)),
            }
        }
        if let Some(package) = current.take() {
            packages.insert(package.url.clone(), package);
        }
        Ok(Self { packages })
    }

    pub fn save(&self, path: &Path) -> Result<(), String> {
        let mut out = String::from("# Generated by lt. Do not edit by hand.\n");
        for package in self.packages.values() {
            out.push_str("\n[[package]]\n");
            out.push_str(&format!("url = \"{}\"\n", package.url));
            out.push_str(&format!("canonical = \"{}\"\n", package.canonical));
            if let Some(commit) = &package.commit {
                out.push_str(&format!("commit = \"{commit}\"\n"));
            }
            out.push_str(&format!("sha256 = \"{}\"\n", package.sha256));
        }
        std::fs::write(path, out).map_err(|error| format!("{}: {error}", path.display()))
    }
}

pub trait HttpFetcher {
    fn get(&mut self, url: &str) -> Result<Vec<u8>, String>;
}

pub struct CurlFetcher;

impl HttpFetcher for CurlFetcher {
    fn get(&mut self, url: &str) -> Result<Vec<u8>, String> {
        let mut command = Command::new("curl");
        command.args(["-fsSL", "--max-time", "60", "--retry", "2"]);
        if let Ok(token) = std::env::var("GITHUB_TOKEN") {
            if url.contains("api.github.com") {
                command
                    .arg("-H")
                    .arg(format!("Authorization: Bearer {token}"));
            }
        }
        command.arg(url);
        let output = command
            .output()
            .map_err(|error| format!("cannot run curl: {error}"))?;
        if !output.status.success() {
            return Err(format!(
                "cannot fetch `{url}`: {}",
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }
        Ok(output.stdout)
    }
}

pub struct Manager {
    pub lock_path: PathBuf,
    pub lock: Lockfile,
    pub cache_dir: PathBuf,
    pub vendor_dir: PathBuf,
    pub mode: Mode,
    http: Box<dyn HttpFetcher>,
    dirty: bool,
    pub fetched: Vec<String>,
}

impl Manager {
    pub fn new(project_root: &Path, mode: Mode) -> Self {
        Self::with_fetcher(project_root, mode, Box::new(CurlFetcher))
    }

    pub fn with_fetcher(project_root: &Path, mode: Mode, http: Box<dyn HttpFetcher>) -> Self {
        let lock_path = project_root.join("lt.lock");
        let lock = Lockfile::load(&lock_path).unwrap_or_default();
        Self {
            lock_path,
            lock,
            cache_dir: cache_dir(),
            vendor_dir: project_root.join("vendor"),
            mode,
            http,
            dirty: false,
            fetched: Vec::new(),
        }
    }

    pub fn save(&mut self) -> Result<(), String> {
        if self.dirty {
            self.lock.save(&self.lock_path)?;
            self.dirty = false;
        }
        Ok(())
    }

    /// Copy every locked object into `vendor/`, so builds work offline.
    pub fn vendor(&mut self) -> Result<usize, String> {
        std::fs::create_dir_all(&self.vendor_dir)
            .map_err(|error| format!("{}: {error}", self.vendor_dir.display()))?;
        let mut count = 0;
        for package in self.lock.packages.values() {
            let source = self.cache_dir.join("objects").join(&package.sha256);
            let target = self.vendor_dir.join(&package.sha256);
            if target.is_file() {
                count += 1;
                continue;
            }
            if source.is_file() {
                std::fs::copy(&source, &target)
                    .map_err(|error| format!("{}: {error}", target.display()))?;
                count += 1;
            } else if let Some(bytes) = self.read_vendor(&package.sha256) {
                let _ = bytes;
                count += 1;
            }
        }
        Ok(count)
    }

    fn object_path(&self, sha256: &str) -> PathBuf {
        self.cache_dir.join("objects").join(sha256)
    }

    fn read_vendor(&self, sha256: &str) -> Option<Vec<u8>> {
        std::fs::read(self.vendor_dir.join(sha256)).ok()
    }

    fn read_cache(&self, sha256: &str) -> Option<Vec<u8>> {
        std::fs::read(self.object_path(sha256)).ok()
    }

    fn store(&self, sha256: &str, bytes: &[u8]) -> Result<(), String> {
        let objects = self.cache_dir.join("objects");
        std::fs::create_dir_all(&objects)
            .map_err(|error| format!("{}: {error}", objects.display()))?;
        let target = objects.join(sha256);
        if target.is_file() {
            return Ok(());
        }
        let temporary = objects.join(format!("{sha256}.tmp{}", std::process::id()));
        std::fs::write(&temporary, bytes)
            .map_err(|error| format!("{}: {error}", temporary.display()))?;
        std::fs::rename(&temporary, &target)
            .map_err(|error| format!("{}: {error}", target.display()))?;
        Ok(())
    }

    fn fetch_verified(&mut self, url: &str, expected: &str) -> Result<ResolvedRemote, String> {
        let bytes = self.http.get(url)?;
        let sum = sha256_hex(&bytes);
        if sum != expected {
            return Err(format!(
                "checksum mismatch for `{url}`: lock says {expected}, fetched {sum}; run `lt update` to accept the new content"
            ));
        }
        self.store(&sum, &bytes)?;
        self.fetched.push(url.to_string());
        Ok(ResolvedRemote {
            canonical_url: url.to_string(),
            content: from_utf8(&bytes)?,
            sha256: sum,
        })
    }

    fn resolve_fresh(&mut self, url: &str) -> Result<ResolvedRemote, String> {
        let (canonical, commit) = match resolve_commit(&mut *self.http, url) {
            Some((canonical, commit)) => (canonical, Some(commit)),
            None => (url.to_string(), None),
        };
        let bytes = self.http.get(&canonical)?;
        let sum = sha256_hex(&bytes);
        self.store(&sum, &bytes)?;
        self.fetched.push(canonical.clone());
        self.lock.packages.insert(
            url.to_string(),
            Package {
                url: url.to_string(),
                canonical: canonical.clone(),
                commit,
                sha256: sum.clone(),
            },
        );
        self.dirty = true;
        Ok(ResolvedRemote {
            canonical_url: canonical,
            content: from_utf8(&bytes)?,
            sha256: sum,
        })
    }
}

impl RemoteResolver for Manager {
    fn resolve(&mut self, url: &str) -> Result<ResolvedRemote, String> {
        if self.mode == Mode::Update {
            return self.resolve_fresh(url);
        }

        let Some(package) = self.lock.packages.get(url).cloned() else {
            return self.resolve_fresh(url);
        };

        if let Some(bytes) = self.read_vendor(&package.sha256) {
            let sum = sha256_hex(&bytes);
            if sum == package.sha256 {
                return Ok(ResolvedRemote {
                    canonical_url: package.canonical.clone(),
                    content: from_utf8(&bytes)?,
                    sha256: sum,
                });
            }
        }

        if let Some(bytes) = self.read_cache(&package.sha256) {
            let sum = sha256_hex(&bytes);
            if sum == package.sha256 {
                return Ok(ResolvedRemote {
                    canonical_url: package.canonical.clone(),
                    content: from_utf8(&bytes)?,
                    sha256: sum,
                });
            }
        }

        let target = if package.canonical.is_empty() {
            url.to_string()
        } else {
            package.canonical.clone()
        };
        self.fetch_verified(&target, &package.sha256)
    }
}

fn from_utf8(bytes: &[u8]) -> Result<String, String> {
    String::from_utf8(bytes.to_vec()).map_err(|_| "remote file is not valid UTF-8".to_string())
}

pub fn sha256_hex(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    let digest = hasher.finalize();
    digest.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn cache_dir() -> PathBuf {
    if let Ok(dir) = std::env::var("LT_CACHE_DIR") {
        return PathBuf::from(dir);
    }
    if let Ok(dir) = std::env::var("XDG_CACHE_HOME") {
        return PathBuf::from(dir).join("lt");
    }
    let home = std::env::var("HOME").unwrap_or_else(|_| ".".to_string());
    PathBuf::from(home).join(".cache").join("lt")
}

/// For `raw.githubusercontent.com/<owner>/<repo>/<ref>/<path>` URLs, resolve
/// `<ref>` to a commit SHA through the GitHub API so the content is immutable.
fn resolve_commit(http: &mut dyn HttpFetcher, url: &str) -> Option<(String, String)> {
    let rest = url.strip_prefix("https://raw.githubusercontent.com/")?;
    let mut parts = rest.splitn(4, '/');
    let owner = parts.next()?;
    let repo = parts.next()?;
    let reference = parts.next()?;
    let path = parts.next()?;
    if reference.len() == 40 && reference.chars().all(|ch| ch.is_ascii_hexdigit()) {
        return Some((url.to_string(), reference.to_string()));
    }

    let api = format!("https://api.github.com/repos/{owner}/{repo}/commits/{reference}");
    let bytes = http.get(&api).ok()?;
    let text = String::from_utf8(bytes).ok()?;
    let marker = "\"sha\"";
    let index = text.find(marker)?;
    let after = &text[index + marker.len()..];
    let quote = after.find('"')?;
    let value = &after[quote + 1..];
    let end = value.find('"')?;
    let sha = &value[..end];
    if sha.len() != 40 || !sha.chars().all(|ch| ch.is_ascii_hexdigit()) {
        return None;
    }
    Some((
        format!("https://raw.githubusercontent.com/{owner}/{repo}/{sha}/{path}"),
        sha.to_string(),
    ))
}
