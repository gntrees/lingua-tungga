//! TypeScript emitter: renders the typed IR as strict-mode TypeScript.

use std::collections::BTreeSet;

use lt_hir::{ModuleId, Ty};
use lt_ir::*;

const RESERVED: &[&str] = &[
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do",
    "else", "enum", "export", "extends", "false", "finally", "for", "function", "if", "import",
    "in", "instanceof", "new", "null", "return", "super", "switch", "this", "throw", "true", "try",
    "typeof", "var", "void", "while", "with", "yield", "let", "static", "await", "implements",
    "interface", "package", "private", "protected", "public", "constructor",
];

fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for ch in name.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    if RESERVED.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

fn quote(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            ch if (ch as u32) < 0x20 => out.push_str(&format!("\\u{{{:x}}}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn indent(level: usize) -> String {
    "  ".repeat(level)
}

fn module_import_path(from: &str, to: &str) -> String {
    let from_parts: Vec<&str> = from.split('/').collect();
    let to_parts: Vec<&str> = to.split('/').collect();
    let from_dir = &from_parts[..from_parts.len().saturating_sub(1)];
    let to_dir = &to_parts[..to_parts.len().saturating_sub(1)];

    let mut common = 0;
    while common < from_dir.len() && common < to_dir.len() && from_dir[common] == to_dir[common] {
        common += 1;
    }

    let mut out = String::from("./");
    for _ in common..from_dir.len() {
        out.push_str("../");
    }
    for segment in &to_dir[common..] {
        out.push_str(segment);
        out.push('/');
    }
    out.push_str(to_parts.last().copied().unwrap_or("index"));
    out
}

fn runtime_path(module_name: &str) -> String {
    let depth = module_name.matches('/').count();
    format!("{}_lingua_rt", "../".repeat(depth + 1))
}

#[derive(Clone)]
enum Tail {
    Plain,
    Return,
    Assign(String),
}

struct Frag {
    prelude: Vec<String>,
    code: String,
}

pub fn emit_module(program: &IrProgram, module: &IrModule) -> String {
    let mut emitter = Emitter {
        module,
        temps: 0,
        used: BTreeSet::new(),
        tests_mode: false,
    };

    let mut body = String::new();
    for decl in &module.enums {
        body.push_str(&emitter.enum_decl(decl));
        body.push('\n');
    }
    for class in &module.classes {
        body.push_str(&emitter.class_decl(class));
        body.push('\n');
    }

    let used: Vec<ModuleId> = emitter.used.iter().copied().collect();
    let mut header = String::from("// Generated by Lingua Tungga. Do not edit by hand.\n");
    header.push_str(&format!(
        "import * as lt from \"{}\";\n",
        runtime_path(&module.name)
    ));
    for id in used {
        header.push_str(&format!(
            "import * as m{} from \"{}\";\n",
            id,
            module_import_path(&module.name, &program.names[id])
        ));
    }
    header.push('\n');
    header.push_str(&body);
    header
}

/// Emit the `vitest` file for one module, if it declares test classes.
pub fn emit_tests(program: &IrProgram, module: &IrModule) -> Option<String> {
    if module.tests.iter().all(|test| test.tests.is_empty()) {
        return None;
    }

    let mut emitter = Emitter {
        module,
        temps: 0,
        used: BTreeSet::new(),
        tests_mode: true,
    };

    let mut body = String::new();
    for test_class in &module.tests {
        for helper in &test_class.helpers {
            body.push_str(&emitter.free_function(helper));
            body.push('\n');
        }
        body.push_str(&format!("describe({}, () => {{\n", quote(&test_class.name)));
        for (index, test) in test_class.tests.iter().enumerate() {
            if index > 0 {
                body.push('\n');
            }
            body.push_str(&format!("  it({}, () => {{\n", quote(&test.name)));
            for line in emitter.block_lines(&test.body, 2, &Tail::Plain) {
                body.push_str(&line);
                body.push('\n');
            }
            body.push_str("  });\n");
        }
        body.push_str("});\n");
    }

    let depth = module.name.matches('/').count() + 1;
    let used: Vec<ModuleId> = emitter.used.iter().copied().collect();
    let mut header = String::from("// Generated by Lingua Tungga. Do not edit by hand.\n");
    header.push_str("import { describe, it } from \"vitest\";\n");
    header.push_str(&format!(
        "import * as lt from \"{}_lingua_rt\";\n",
        "../".repeat(depth)
    ));
    for id in used {
        header.push_str(&format!(
            "import * as m{} from \"{}src/{}\";\n",
            id,
            "../".repeat(depth),
            program.names[id]
        ));
    }
    header.push('\n');
    header.push_str(&body);
    Some(header)
}

struct Emitter<'a> {
    module: &'a IrModule,
    temps: usize,
    used: BTreeSet<ModuleId>,
    tests_mode: bool,
}

impl<'a> Emitter<'a> {
    // ------------------------------------------------------------- helpers

    fn temp(&mut self, prefix: &str) -> String {
        self.temps += 1;
        format!("__{prefix}{}", self.temps)
    }

    fn use_module(&mut self, module: ModuleId) {
        if module != self.module.id || self.tests_mode {
            self.used.insert(module);
        }
    }

    /// Is this module rendered with local names (not through an `mN` alias)?
    fn is_local(&self, module: ModuleId) -> bool {
        module == self.module.id && !self.tests_mode
    }

    fn type_ref(&mut self, ty: &Ty) -> String {
        match ty {
            Ty::Int => "bigint".to_string(),
            Ty::Float => "number".to_string(),
            Ty::Bool => "boolean".to_string(),
            Ty::Str => "string".to_string(),
            Ty::Unit => "lt.Unit".to_string(),
            Ty::List(inner) => format!("lt.LList<{}>", self.type_ref(inner)),
            Ty::Set(inner) => format!("lt.LSet<{}>", self.type_ref(inner)),
            Ty::Option(inner) => format!("lt.Opt<{}>", self.type_ref(inner)),
            Ty::Map(key, value) => {
                format!("lt.LMap<{}, {}>", self.type_ref(key), self.type_ref(value))
            }
            Ty::Result(ok, err) => {
                format!("lt.Res<{}, {}>", self.type_ref(ok), self.type_ref(err))
            }
            Ty::Named(name, args) => {
                self.use_module(name.module);
                let base = if self.is_local(name.module) {
                    name.name.clone()
                } else {
                    format!("m{}.{}", name.module, name.name)
                };
                if args.is_empty() {
                    base
                } else {
                    let rendered: Vec<String> = args.iter().map(|arg| self.type_ref(arg)).collect();
                    format!("{base}<{}>", rendered.join(", "))
                }
            }
            Ty::Generic(name) => name.clone(),
            Ty::Var(_) | Ty::Error => "unknown".to_string(),
        }
    }

    fn return_type(&mut self, ty: &Ty) -> String {
        if matches!(ty, Ty::Unit) {
            "void".to_string()
        } else {
            self.type_ref(ty)
        }
    }

    fn class_ref(&mut self, module: ModuleId, name: &str) -> String {
        self.use_module(module);
        if self.is_local(module) {
            name.to_string()
        } else {
            format!("m{}.{}", module, name)
        }
    }

    fn variant_ref(&mut self, module: ModuleId, enum_name: &str, variant: &str) -> String {
        self.use_module(module);
        let local = format!("{enum_name}_{variant}");
        if self.is_local(module) {
            local
        } else {
            format!("m{}.{}", module, local)
        }
    }

    fn generics<T: AsRef<str>>(names: &[T]) -> String {
        if names.is_empty() {
            String::new()
        } else {
            format!("<{}>", names.iter().map(AsRef::as_ref).collect::<Vec<_>>().join(", "))
        }
    }

    // --------------------------------------------------------------- decls

    fn enum_decl(&mut self, decl: &IrEnum) -> String {
        let mut out = String::new();
        let generic_names: Vec<String> = decl.generics.clone();
        let generics = Self::generics(&generic_names);
        let applied = if generic_names.is_empty() {
            decl.name.clone()
        } else {
            format!("{}<{}>", decl.name, generic_names.join(", "))
        };

        out.push_str(&format!("export type {}{} =\n", decl.name, generics));
        for (index, variant) in decl.variants.iter().enumerate() {
            let payload: Vec<String> = variant.payload.iter().map(|ty| self.type_ref(ty)).collect();
            let tuple = if payload.is_empty() {
                String::new()
            } else {
                payload.join(", ")
            };
            out.push_str(&format!(
                "  | {{ readonly tag: {}; readonly values: readonly [{}]; readonly __lt_display: (value: any) => string; readonly __lt_order: number }}\n",
                quote(&variant.name),
                tuple
            ));
            let _ = index;
        }
        out.push('\n');

        for (order, variant) in decl.variants.iter().enumerate() {
            let constructor = format!("{}_{}", decl.name, variant.name);
            if variant.payload.is_empty() {
                out.push_str(&format!(
                    "export const {constructor}{generics}: {applied} = {{ tag: {}, values: [], __lt_order: {order}, __lt_display: {}_display }};\n",
                    quote(&variant.name),
                    decl.name
                ));
            } else {
                let params: Vec<String> = variant
                    .payload
                    .iter()
                    .enumerate()
                    .map(|(index, ty)| format!("_{index}: {}", self.type_ref(ty)))
                    .collect();
                let values: Vec<String> = (0..variant.payload.len())
                    .map(|index| format!("_{index}"))
                    .collect();
                out.push_str(&format!(
                    "export function {constructor}{generics}({}): {applied} {{\n  return {{ tag: {}, values: [{}], __lt_order: {order}, __lt_display: {}_display }};\n}}\n",
                    params.join(", "),
                    quote(&variant.name),
                    values.join(", "),
                    decl.name
                ));
            }
        }

        out.push_str(&format!(
            "export function {}_display{}(value: {}): string {{\n",
            decl.name, generics, applied
        ));
        out.push_str("  switch (value.tag) {\n");
        for variant in &decl.variants {
            out.push_str(&format!("    case {}: {{\n", quote(&variant.name)));
            if variant.payload.is_empty() {
                out.push_str(&format!(
                    "      return {};\n",
                    quote(&format!("{}.{}", decl.name, variant.name))
                ));
            } else {
                let pieces: Vec<String> = variant
                    .payload
                    .iter()
                    .enumerate()
                    .map(|(index, _)| format!("${{lt.disp(value.values[{index}])}}"))
                    .collect();
                out.push_str(&format!(
                    "      return `{}.{}({})`;\n",
                    decl.name,
                    variant.name,
                    pieces.join(", ")
                ));
            }
            out.push_str("    }\n");
        }
        out.push_str("    default:\n      throw new Error(\"unreachable\");\n  }\n}\n");
        out
    }

    fn class_decl(&mut self, class: &IrClass) -> String {
        let generic_names = class.generics.clone();
        let generics = Self::generics(&generic_names);
        let mut out = format!("export class {}{} {{\n", class.name, generics);

        for field in &class.fields {
            out.push_str(&format!(
                "  readonly {}: {};\n",
                camel(&field.name),
                self.type_ref(&field.ty)
            ));
        }

        if !class.fields.is_empty() {
            let fields: Vec<String> = class
                .fields
                .iter()
                .map(|field| format!("{}: {}", camel(&field.name), self.type_ref(&field.ty)))
                .collect();
            out.push_str(&format!("\n  constructor(fields: {{ {} }}) {{\n", fields.join("; ")));
            for field in &class.fields {
                let name = camel(&field.name);
                out.push_str(&format!("    this.{name} = fields.{name};\n"));
            }
            out.push_str("  }\n");
        }

        for method in &class.methods {
            out.push('\n');
            out.push_str(&self.method_decl(method));
        }

        out.push_str("\n  __lt_eq(other: unknown): boolean {\n");
        out.push_str(&format!("    if (!(other instanceof {})) return false;\n", class.name));
        if class.fields.is_empty() {
            out.push_str("    return true;\n");
        } else {
            let checks: Vec<String> = class
                .fields
                .iter()
                .map(|field| {
                    let name = camel(&field.name);
                    let cast = if class.generics.is_empty() {
                        class.name.clone()
                    } else {
                        format!("{}<any>", class.name)
                    };
                    format!("lt.eq(this.{name}, (other as {cast}).{name})")
                })
                .collect();
            out.push_str(&format!("    return {};\n", checks.join(" && ")));
        }
        out.push_str("  }\n");

        out.push_str("\n  __lt_cmp(other: unknown): number {\n");
        let cast = if class.generics.is_empty() {
            class.name.clone()
        } else {
            format!("{}<any>", class.name)
        };
        out.push_str(&format!("    if (!(other instanceof {})) return 0;\n", class.name));
        out.push_str(&format!("    const peer = other as {cast};\n"));
        for field in &class.fields {
            let name = camel(&field.name);
            out.push_str(&format!(
                "    const {}Result = lt.cmp(this.{name}, peer.{name});\n",
                name
            ));
            out.push_str(&format!(
                "    if ({}Result !== 0) return {}Result;\n",
                name, name
            ));
        }
        out.push_str("    return 0;\n  }\n");

        out.push_str("\n  __lt_to_string(): string {\n");
        if class.fields.is_empty() {
            out.push_str(&format!("    return {};\n", quote(&class.name)));
        } else {
            let pieces: Vec<String> = class
                .fields
                .iter()
                .map(|field| {
                    format!(
                        "{}: ${{lt.disp(this.{})}}",
                        field.name,
                        camel(&field.name)
                    )
                })
                .collect();
            out.push_str(&format!(
                "    return `{}({})`;\n",
                class.name,
                pieces.join(", ")
            ));
        }
        out.push_str("  }\n");

        out.push_str("}\n");
        out
    }

    fn method_decl(&mut self, method: &IrMethod) -> String {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|param| format!("{}: {}", camel(&param.name), self.type_ref(&param.ty)))
            .collect();
        let static_kw = if method.is_static { "static " } else { "" };
        let ret = self.return_type(&method.ret);
        let mut out = format!(
            "  {static_kw}{}({}): {ret} {{\n",
            camel(&method.name),
            params.join(", ")
        );
        let tail = if matches!(method.ret, Ty::Unit) {
            Tail::Plain
        } else {
            Tail::Return
        };
        for line in self.block_lines(&method.body, 2, &tail) {
            out.push_str(&line);
            out.push('\n');
        }
        out.push_str("  }\n");
        out
    }

    fn free_function(&mut self, method: &IrMethod) -> String {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|param| format!("{}: {}", camel(&param.name), self.type_ref(&param.ty)))
            .collect();
        let ret = self.return_type(&method.ret);
        let mut out = format!(
            "function {}({}): {ret} {{\n",
            camel(&method.name),
            params.join(", ")
        );
        let tail = if matches!(method.ret, Ty::Unit) {
            Tail::Plain
        } else {
            Tail::Return
        };
        for line in self.block_lines(&method.body, 1, &tail) {
            out.push_str(&line);
            out.push('\n');
        }
        out.push_str("}\n");
        out
    }

    // ------------------------------------------------------------ statements

    fn block_lines(&mut self, block: &IrBlock, level: usize, tail: &Tail) -> Vec<String> {
        let mut lines = Vec::new();
        let count = block.stmts.len();
        for (index, stmt) in block.stmts.iter().enumerate() {
            let is_last = index + 1 == count;
            let stmt_tail = if is_last {
                tail.clone()
            } else {
                Tail::Plain
            };
            lines.extend(self.stmt(stmt, level, &stmt_tail));
        }
        lines
    }

    fn stmt(&mut self, stmt: &IrStmt, level: usize, tail: &Tail) -> Vec<String> {
        let pad = indent(level);
        match stmt {
            IrStmt::Let {
                name,
                ty,
                mutable,
                value,
            } => {
                let frag = self.expr(value, level);
                let mut lines = frag.prelude;
                let keyword = if *mutable { "let" } else { "const" };
                lines.push(format!(
                    "{pad}{keyword} {}: {} = {};",
                    camel(name),
                    self.type_ref(ty),
                    frag.code
                ));
                lines
            }
            IrStmt::Assign { name, value } => {
                let frag = self.expr(value, level);
                let mut lines = frag.prelude;
                lines.push(format!("{pad}{} = {};", camel(name), frag.code));
                lines
            }
            IrStmt::Return(value) => {
                let mut lines = Vec::new();
                match value {
                    Some(value) => {
                        let frag = self.expr(value, level);
                        lines.extend(frag.prelude);
                        lines.push(format!("{pad}return {};", frag.code));
                    }
                    None => lines.push(format!("{pad}return;")),
                }
                lines
            }
            IrStmt::For {
                var,
                iter,
                body,
                ..
            } => {
                let frag = self.expr(iter, level);
                let mut lines = frag.prelude;
                lines.push(format!(
                    "{pad}for (const {} of {}.items) {{",
                    camel(var),
                    frag.code
                ));
                lines.extend(self.block_lines(body, level + 1, &Tail::Plain));
                lines.push(format!("{pad}}}"));
                lines
            }
            IrStmt::While { cond, body } => {
                let frag = self.expr(cond, level);
                let mut lines = frag.prelude;
                lines.push(format!("{pad}while ({}) {{", frag.code));
                lines.extend(self.block_lines(body, level + 1, &Tail::Plain));
                lines.push(format!("{pad}}}"));
                lines
            }
            IrStmt::Expr(expr) => match expr {
                IrExpr::If { .. } => self.if_stmt(expr, level, tail),
                IrExpr::Match { .. } => self.match_stmt(expr, level, tail),
                other => {
                    let frag = self.expr(other, level);
                    let mut lines = frag.prelude;
                    match tail {
                        Tail::Plain => lines.push(format!("{pad}{};", frag.code)),
                        Tail::Return => lines.push(format!("{pad}return {};", frag.code)),
                        Tail::Assign(target) => {
                            lines.push(format!("{pad}{target} = {};", frag.code))
                        }
                    }
                    lines
                }
            },
        }
    }

    fn if_stmt(&mut self, expr: &IrExpr, level: usize, tail: &Tail) -> Vec<String> {
        let IrExpr::If {
            cond,
            then_block,
            else_branch,
            ..
        } = expr
        else {
            unreachable!("if_stmt expects an `if`")
        };
        let pad = indent(level);
        let cond_frag = self.expr(cond, level);
        let mut lines = cond_frag.prelude;
        lines.push(format!("{pad}if ({}) {{", cond_frag.code));
        lines.extend(self.block_lines(then_block, level + 1, tail));

        let mut current = else_branch;
        loop {
            match current {
                None => {
                    lines.push(format!("{pad}}}"));
                    break;
                }
                Some(IrElse::Block(block)) => {
                    lines.push(format!("{pad}}} else {{"));
                    lines.extend(self.block_lines(block, level + 1, tail));
                    lines.push(format!("{pad}}}"));
                    break;
                }
                Some(IrElse::If(nested)) => {
                    if let IrExpr::If {
                        cond,
                        then_block,
                        else_branch,
                        ..
                    } = nested.as_ref()
                    {
                        let cond_frag = self.expr(cond, level);
                        lines.extend(cond_frag.prelude);
                        lines.push(format!("{pad}}} else if ({}) {{", cond_frag.code));
                        lines.extend(self.block_lines(then_block, level + 1, tail));
                        current = else_branch;
                    } else {
                        lines.push(format!("{pad}}}"));
                        break;
                    }
                }
            }
        }
        lines
    }

    fn match_stmt(&mut self, expr: &IrExpr, level: usize, tail: &Tail) -> Vec<String> {
        let IrExpr::Match {
            scrutinee, arms, ..
        } = expr
        else {
            unreachable!("match_stmt expects a `match`")
        };
        let pad = indent(level);
        let scrutinee_frag = self.expr(scrutinee, level);
        let binding = self.temp("match");
        let mut lines = scrutinee_frag.prelude;
        lines.push(format!(
            "{pad}const {binding} = {};",
            scrutinee_frag.code
        ));
        lines.push(format!("{pad}switch ({binding}.tag) {{"));

        let needs_break = !matches!(tail, Tail::Return);
        let mut catch_all = false;
        for arm in arms {
            match &arm.pattern {
                IrPattern::Variant { variant, bindings } => {
                    lines.push(format!("{pad}  case {}: {{", quote(variant)));
                    for (index, (name, ty)) in bindings.iter().enumerate() {
                        lines.push(format!(
                            "{pad}    const {}: {} = {binding}.values[{index}];",
                            camel(name),
                            self.type_ref(ty)
                        ));
                    }
                    lines.extend(self.block_lines(&arm.body, level + 2, tail));
                    if needs_break {
                        lines.push(format!("{pad}    break;"));
                    }
                    lines.push(format!("{pad}  }}"));
                }
                IrPattern::Binding { name, ty } => {
                    catch_all = true;
                    lines.push(format!("{pad}  default: {{"));
                    lines.push(format!(
                        "{pad}    const {}: {} = {binding};",
                        camel(name),
                        self.type_ref(ty)
                    ));
                    lines.extend(self.block_lines(&arm.body, level + 2, tail));
                    if needs_break {
                        lines.push(format!("{pad}    break;"));
                    }
                    lines.push(format!("{pad}  }}"));
                }
                IrPattern::Wildcard => {
                    catch_all = true;
                    lines.push(format!("{pad}  default: {{"));
                    lines.extend(self.block_lines(&arm.body, level + 2, tail));
                    if needs_break {
                        lines.push(format!("{pad}    break;"));
                    }
                    lines.push(format!("{pad}  }}"));
                }
            }
        }

        if !catch_all {
            lines.push(format!(
                "{pad}  default:\n{pad}    throw new Error(\"unreachable\");"
            ));
        }

        lines.push(format!("{pad}}}"));
        lines
    }

    // ----------------------------------------------------------- expressions

    fn expr(&mut self, expr: &IrExpr, level: usize) -> Frag {
        match expr {
            IrExpr::Int(value) => Frag {
                prelude: Vec::new(),
                code: format!("{value}n"),
            },
            IrExpr::Float(value) => Frag {
                prelude: Vec::new(),
                code: format_float(*value),
            },
            IrExpr::Str(value) => Frag {
                prelude: Vec::new(),
                code: quote(value),
            },
            IrExpr::Bool(value) => Frag {
                prelude: Vec::new(),
                code: value.to_string(),
            },
            IrExpr::Var(name) => Frag {
                prelude: Vec::new(),
                code: camel(name),
            },
            IrExpr::SelfRef => Frag {
                prelude: Vec::new(),
                code: "this".to_string(),
            },
            IrExpr::List { items, ty } => {
                let element = match ty {
                    Ty::List(inner) => self.type_ref(inner),
                    _ => "unknown".to_string(),
                };
                let mut prelude = Vec::new();
                let rendered: Vec<String> = items
                    .iter()
                    .map(|item| {
                        let frag = self.expr(item, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("new lt.LList<{element}>([{}])", rendered.join(", ")),
                }
            }
            IrExpr::EmptyCollection { ty } => {
                let code = match ty {
                    Ty::Map(key, value) => format!(
                        "lt.LMap.empty<{}, {}>()",
                        self.type_ref(key),
                        self.type_ref(value)
                    ),
                    Ty::Set(inner) => format!("new lt.LSet<{}>([])", self.type_ref(inner)),
                    _ => "new lt.LList<unknown>([])".to_string(),
                };
                Frag {
                    prelude: Vec::new(),
                    code,
                }
            }
            IrExpr::Field { base, name, .. } => {
                let frag = self.expr(base, level);
                Frag {
                    prelude: frag.prelude,
                    code: format!("{}.{}", frag.code, camel(name)),
                }
            }
            IrExpr::ClassNew {
                module,
                class,
                args,
                ..
            } => {
                let class_ref = self.class_ref(*module, class);
                let mut prelude = Vec::new();
                let fields: Vec<String> = args
                    .iter()
                    .map(|(name, value)| {
                        let frag = self.expr(value, level);
                        prelude.extend(frag.prelude);
                        format!("{}: {}", camel(name), frag.code)
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("new {class_ref}({{ {} }})", fields.join(", ")),
                }
            }
            IrExpr::NewVariant {
                target, variant, args, ..
            } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let code = match target {
                    VariantRef::Option => {
                        if variant == "Some" {
                            format!("lt.Some({})", rendered.join(", "))
                        } else {
                            "lt.None()".to_string()
                        }
                    }
                    VariantRef::Result => {
                        if variant == "Ok" {
                            format!("lt.Ok({})", rendered.join(", "))
                        } else {
                            format!("lt.Err({})", rendered.join(", "))
                        }
                    }
                    VariantRef::Enum { module, name } => {
                        let reference = self.variant_ref(*module, name, variant);
                        if rendered.is_empty() {
                            reference
                        } else {
                            format!("{reference}({})", rendered.join(", "))
                        }
                    }
                };
                Frag { prelude, code }
            }
            IrExpr::LocalCall { name, args, .. } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{}({})", camel(name), rendered.join(", ")),
                }
            }
            IrExpr::StaticCall {
                module,
                class,
                method,
                args,
                ..
            } => {
                let class_ref = self.class_ref(*module, class);
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{class_ref}.{}({})", camel(method), rendered.join(", ")),
                }
            }
            IrExpr::InstanceCall {
                receiver,
                method,
                args,
                ..
            } => {
                let recv = self.expr(receiver, level);
                let mut prelude = recv.prelude;
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{}.{}({})", recv.code, camel(method), rendered.join(", ")),
                }
            }
            IrExpr::Builtin {
                kind,
                receiver,
                args,
                ..
            } => {
                let recv = self.expr(receiver, level);
                let mut prelude = recv.prelude;
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: self.builtin(*kind, &recv.code, &rendered),
                }
            }
            IrExpr::Math { name, args, .. } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let code = match name.as_str() {
                    "pi" => "Math.PI".to_string(),
                    other => format!("Math.{other}({})", rendered.join(", ")),
                };
                Frag { prelude, code }
            }
            IrExpr::Expect { name, args } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let function = match name.as_str() {
                    "equal" => "expectEqual",
                    "not_equal" => "expectNotEqual",
                    "true" => "expectTrue",
                    "false" => "expectFalse",
                    other => other,
                };
                Frag {
                    prelude,
                    code: format!("lt.{function}({})", rendered.join(", ")),
                }
            }
            IrExpr::ToStr { value, .. } => {
                let frag = self.expr(value, level);
                Frag {
                    prelude: frag.prelude,
                    code: format!("lt.disp({})", frag.code),
                }
            }
            IrExpr::Template { parts, exprs } => {
                let mut prelude = Vec::new();
                let mut code = quote(parts.first().map(String::as_str).unwrap_or(""));
                for (index, inner) in exprs.iter().enumerate() {
                    let frag = self.expr(inner, level);
                    prelude.extend(frag.prelude);
                    code.push_str(&format!(" + lt.disp({})", frag.code));
                    if let Some(part) = parts.get(index + 1) {
                        if !part.is_empty() {
                            code.push_str(&format!(" + {}", quote(part)));
                        }
                    }
                }
                Frag { prelude, code }
            }
            IrExpr::Try {
                value, source_ty, ..
            } => {
                let frag = self.expr(value, level);
                let mut prelude = frag.prelude;
                let temp = self.temp("try");
                let pad = indent(level);
                let error_tag = match source_ty {
                    Ty::Option(_) => "none",
                    _ => "err",
                };
                prelude.push(format!("{pad}const {temp} = {};", frag.code));
                prelude.push(format!(
                    "{pad}if ({temp}.tag === {}) return {temp};",
                    quote(error_tag)
                ));
                Frag {
                    prelude,
                    code: format!("{temp}.values[0]"),
                }
            }
            IrExpr::If { ty, .. } => {
                let target = self.temp("if");
                let pad = indent(level);
                let mut prelude = vec![format!(
                    "{pad}let {target}: {};",
                    self.type_ref(ty)
                )];
                prelude.extend(self.if_stmt(expr, level, &Tail::Assign(target.clone())));
                Frag {
                    prelude,
                    code: target,
                }
            }
            IrExpr::Match { ty, .. } => {
                let target = self.temp("match");
                let pad = indent(level);
                let mut prelude = vec![format!(
                    "{pad}let {target}: {};",
                    self.type_ref(ty)
                )];
                prelude.extend(self.match_stmt(expr, level, &Tail::Assign(target.clone())));
                Frag {
                    prelude,
                    code: target,
                }
            }
            IrExpr::Bin { op, lhs, rhs, ty } => {
                let left = self.expr(lhs, level);
                let right = self.expr(rhs, level);
                let mut prelude = left.prelude;
                prelude.extend(right.prelude);
                let code = self.binary(*op, &left.code, &right.code, ty);
                Frag { prelude, code }
            }
            IrExpr::Un { op, value, ty } => {
                let frag = self.expr(value, level);
                let code = match (op, ty) {
                    (UnOp::Not, _) => format!("!({})", frag.code),
                    (UnOp::Neg, Ty::Int) => format!("lt.ineg({})", frag.code),
                    (UnOp::Neg, _) => format!("(-{})", frag.code),
                };
                Frag {
                    prelude: frag.prelude,
                    code,
                }
            }
            IrExpr::Lambda { params, body, .. } => {
                let params: Vec<String> = params
                    .iter()
                    .map(|param| format!("{}: {}", camel(&param.name), self.type_ref(&param.ty)))
                    .collect();
                let code = match body {
                    IrLambdaBody::Expr(expr) => {
                        let frag = self.expr(expr, level);
                        if frag.prelude.is_empty() {
                            format!("({}) => {}", params.join(", "), frag.code)
                        } else {
                            let mut lines = frag.prelude;
                            lines.push(format!("return {};", frag.code));
                            format!(
                                "({}) => {{\n{}\n{}}}",
                                params.join(", "),
                                lines.join("\n"),
                                indent(level)
                            )
                        }
                    }
                    IrLambdaBody::Block(block) => {
                        let lines = self.block_lines(block, level + 1, &Tail::Return);
                        format!(
                            "({}) => {{\n{}\n{}}}",
                            params.join(", "),
                            lines.join("\n"),
                            indent(level)
                        )
                    }
                };
                Frag {
                    prelude: Vec::new(),
                    code,
                }
            }
        }
    }

    fn binary(&mut self, op: BinOp, left: &str, right: &str, ty: &Ty) -> String {
        match op {
            BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div | BinOp::Rem => {
                let symbol = match op {
                    BinOp::Add => "+",
                    BinOp::Sub => "-",
                    BinOp::Mul => "*",
                    BinOp::Div => "/",
                    _ => "%",
                };
                if matches!(ty, Ty::Int) {
                    let function = match op {
                        BinOp::Add => "iadd",
                        BinOp::Sub => "isub",
                        BinOp::Mul => "imul",
                        BinOp::Div => "idiv",
                        _ => "irem",
                    };
                    format!("lt.{function}({left}, {right})")
                } else {
                    format!("({left} {symbol} {right})")
                }
            }
            BinOp::Eq => format!("lt.eq({left}, {right})"),
            BinOp::Ne => format!("!lt.eq({left}, {right})"),
            BinOp::Lt => format!("({left} < {right})"),
            BinOp::Le => format!("({left} <= {right})"),
            BinOp::Gt => format!("({left} > {right})"),
            BinOp::Ge => format!("({left} >= {right})"),
            BinOp::And => format!("({left} && {right})"),
            BinOp::Or => format!("({left} || {right})"),
        }
    }

    fn builtin(&mut self, kind: Builtin, recv: &str, args: &[String]) -> String {
        let call = |name: &str| format!("{recv}.{name}({})", args.join(", "));
        match kind {
            Builtin::StrLen => format!("lt.strLen({recv})"),
            Builtin::StrTrim => format!("{recv}.trim()"),
            Builtin::StrTrimIndent => format!("lt.strTrimIndent({recv})"),
            Builtin::StrLower => format!("{recv}.toLowerCase()"),
            Builtin::StrUpper => format!("{recv}.toUpperCase()"),
            Builtin::StrSplit => format!("lt.strSplit({recv}, {})", args.join(", ")),
            Builtin::StrStartsWith => format!("{recv}.startsWith({})", args.join(", ")),
            Builtin::StrEndsWith => format!("{recv}.endsWith({})", args.join(", ")),
            Builtin::StrContains => format!("{recv}.includes({})", args.join(", ")),
            Builtin::StrReplace => format!("lt.strReplace({recv}, {})", args.join(", ")),
            Builtin::StrSlice => format!("lt.strSlice({recv}, {})", args.join(", ")),
            Builtin::StrChars => format!("lt.strChars({recv})"),
            Builtin::StrParseInt => format!("lt.strParseInt({recv})"),
            Builtin::StrParseFloat => format!("lt.strParseFloat({recv})"),
            Builtin::ListLen => format!("{recv}.len()"),
            Builtin::ListGet => call("get"),
            Builtin::ListPush => call("push"),
            Builtin::ListPop => format!("{recv}.pop()"),
            Builtin::ListMap => call("map"),
            Builtin::ListFilter => call("filter"),
            Builtin::ListFold => call("fold"),
            Builtin::ListAny => call("any"),
            Builtin::ListAll => call("all"),
            Builtin::ListSort => format!("{recv}.sort()"),
            Builtin::ListReverse => format!("{recv}.reverse()"),
            Builtin::ListConcat => call("concat"),
            Builtin::ListContains => call("contains"),
            Builtin::ListIndexOf => format!("{recv}.index_of({})", args.join(", ")),
            Builtin::ListJoin => call("join"),
            Builtin::SetLen => format!("{recv}.len()"),
            Builtin::SetInsert => call("insert"),
            Builtin::SetRemove => call("remove"),
            Builtin::SetContains => call("contains"),
            Builtin::SetUnion => call("union"),
            Builtin::SetIntersect => call("intersect"),
            Builtin::SetDifference => call("difference"),
            Builtin::MapLen => format!("{recv}.len()"),
            Builtin::MapGet => call("get"),
            Builtin::MapInsert => call("insert"),
            Builtin::MapRemove => call("remove"),
            Builtin::MapKeys => format!("{recv}.keys()"),
            Builtin::MapValues => format!("{recv}.values()"),
            Builtin::MapContainsKey => format!("{recv}.contains_key({})", args.join(", ")),
            Builtin::OptionIsSome => format!("lt.optIsSome({recv})"),
            Builtin::OptionIsNone => format!("lt.optIsNone({recv})"),
            Builtin::OptionUnwrap => format!("lt.optUnwrap({recv})"),
            Builtin::OptionUnwrapOr => format!("lt.optUnwrapOr({recv}, {})", args.join(", ")),
            Builtin::OptionMap => format!("lt.optMap({recv}, {})", args.join(", ")),
            Builtin::OptionAndThen => format!("lt.optAndThen({recv}, {})", args.join(", ")),
            Builtin::ResultIsOk => format!("lt.resIsOk({recv})"),
            Builtin::ResultIsErr => format!("lt.resIsErr({recv})"),
            Builtin::ResultUnwrap => format!("lt.resUnwrap({recv})"),
            Builtin::ResultUnwrapOr => format!("lt.resUnwrapOr({recv}, {})", args.join(", ")),
            Builtin::ResultMap => format!("lt.resMap({recv}, {})", args.join(", ")),
            Builtin::ResultMapErr => format!("lt.resMapErr({recv}, {})", args.join(", ")),
            Builtin::ResultAndThen => format!("lt.resAndThen({recv}, {})", args.join(", ")),
        }
    }
}

fn format_float(value: f64) -> String {
    if value.is_finite() && value.fract() == 0.0 {
        format!("{value:.1}")
    } else {
        format!("{value:?}")
    }
}
