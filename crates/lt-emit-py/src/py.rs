//! Python emitter: renders the typed IR as Python 3.11+.

use std::collections::BTreeSet;

use lt_hir::{ModuleId, Ty};
use lt_ir::*;

const RESERVED: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield", "match", "case",
];

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (index, ch) in name.chars().enumerate() {
        if ch.is_uppercase() {
            if index > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    let mut out = out.trim_start_matches('_').to_string();
    if out.is_empty() {
        out.push('_');
    }
    if RESERVED.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

fn member(name: &str) -> String {
    let mut out = snake(name);
    if RESERVED.contains(&out.as_str()) {
        out.push('_');
    }
    out
}

fn quote(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            ch if (ch as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

#[derive(Clone)]
enum Tail {
    Plain,
    Return,
    Assign(String),
}

struct Frag {
    prelude: Vec<String>,
    code: String,
}

pub fn emit_module(program: &IrProgram, module: &IrModule) -> String {
    let mut emitter = Emitter {
        module,
        temps: 0,
        used: BTreeSet::new(),
        tests_mode: false,
        uses_math: false,
    };

    let mut body = String::new();
    for decl in &module.enums {
        body.push_str(&emitter.enum_decl(decl));
        body.push('\n');
    }
    for class in &module.classes {
        body.push_str(&emitter.class_decl(class));
        body.push('\n');
    }

    emitter.header(program, &body)
}

pub fn emit_tests(program: &IrProgram, module: &IrModule) -> Option<String> {
    if module.tests.iter().all(|test| test.tests.is_empty()) {
        return None;
    }

    let mut emitter = Emitter {
        module,
        temps: 0,
        used: BTreeSet::new(),
        tests_mode: true,
        uses_math: false,
    };

    let mut body = String::new();
    for test_class in &module.tests {
        for helper in &test_class.helpers {
            body.push_str(&emitter.free_function(helper, true));
            body.push('\n');
        }
        for test in &test_class.tests {
            body.push_str(&format!("def test_{}() -> None:\n", snake(&test.name)));
            let lines = emitter.block_lines(&test.body, 1, &Tail::Plain);
            if lines.is_empty() {
                body.push_str("    pass\n");
            }
            for line in lines {
                body.push_str(&line);
                body.push('\n');
            }
            body.push('\n');
        }
    }

    let mut header = String::new();
    header.push_str("# Generated by Lingua Tungga. Do not edit by hand.\n");
    header.push_str("from __future__ import annotations\n\n");
    if emitter.uses_math {
        header.push_str("import math\n");
    }
    header.push_str("import lt_runtime as lt\n");
    header.push_str("from typing import Any\n");
    for id in &emitter.used {
        header.push_str(&format!(
            "import gen.{} as m{}\n",
            program.names[*id].replace('/', "."),
            id
        ));
    }
    header.push('\n');
    Some(header + &body)
}

struct Emitter<'a> {
    module: &'a IrModule,
    temps: usize,
    used: BTreeSet<ModuleId>,
    tests_mode: bool,
    uses_math: bool,
}

impl<'a> Emitter<'a> {
    fn header(&self, program: &IrProgram, body: &str) -> String {
        let mut out = String::new();
        out.push_str("# Generated by Lingua Tungga. Do not edit by hand.\n");
        out.push_str("from __future__ import annotations\n\n");
        if self.uses_math {
            out.push_str("import math\n");
        }
        out.push_str("import lt_runtime as lt\n");
        out.push_str("from dataclasses import dataclass\n");
        for id in &self.used {
            out.push_str(&format!(
                "import gen.{} as m{}\n",
                program.names[*id].replace('/', "."),
                id
            ));
        }
        out.push_str("from typing import Any\n");
        out.push('\n');
        out.push_str(body);
        out
    }

    fn temp(&mut self, prefix: &str) -> String {
        self.temps += 1;
        format!("__{prefix}{}", self.temps)
    }

    fn use_module(&mut self, module: ModuleId) {
        if module != self.module.id || self.tests_mode {
            self.used.insert(module);
        }
    }

    fn is_local(&self, module: ModuleId) -> bool {
        module == self.module.id && !self.tests_mode
    }

    fn type_ref(&mut self, ty: &Ty) -> String {
        match ty {
            Ty::Int => "int".to_string(),
            Ty::Float => "float".to_string(),
            Ty::Bool => "bool".to_string(),
            Ty::Str => "str".to_string(),
            Ty::Unit => "None".to_string(),
            Ty::List(_) => "lt.LList".to_string(),
            Ty::Set(_) => "lt.LSet".to_string(),
            Ty::Map(_, _) => "lt.LMap".to_string(),
            Ty::Option(_) => "lt.Opt".to_string(),
            Ty::Result(_, _) => "lt.Res".to_string(),
            Ty::Named(name, _) => {
                self.use_module(name.module);
                if self.is_local(name.module) {
                    name.name.clone()
                } else {
                    format!("m{}.{}", name.module, name.name)
                }
            }
            Ty::Generic(_) | Ty::Var(_) | Ty::Error => "Any".to_string(),
        }
    }

    fn class_ref(&mut self, module: ModuleId, name: &str) -> String {
        self.use_module(module);
        if self.is_local(module) {
            name.to_string()
        } else {
            format!("m{}.{}", module, name)
        }
    }

    fn variant_ref(&mut self, module: ModuleId, enum_name: &str, variant: &str) -> String {
        self.use_module(module);
        let local = member(&format!("{enum_name}_{variant}"));
        if self.is_local(module) {
            local
        } else {
            format!("m{}.{}", module, local)
        }
    }

    // --------------------------------------------------------------- decls

    fn enum_decl(&mut self, decl: &IrEnum) -> String {
        let mut out = String::new();
        out.push_str("@dataclass(frozen=True)\n");
        out.push_str(&format!("class {}:\n", decl.name));
        out.push_str("    tag: str\n    values: tuple\n    order: int\n\n");
        out.push_str("    def to_display(self) -> str:\n");
        out.push_str(&format!("        return _{}_display(self)\n\n", snake(&decl.name)));

        for (order, variant) in decl.variants.iter().enumerate() {
            let name = member(&format!("{}_{}", decl.name, variant.name));
            if variant.payload.is_empty() {
                out.push_str(&format!(
                    "{} = {}({}, (), {order})\n\n",
                    name,
                    decl.name,
                    quote(&variant.name)
                ));
            } else {
                let params: Vec<String> = variant
                    .payload
                    .iter()
                    .enumerate()
                    .map(|(index, ty)| format!("_{index}: {}", self.type_ref(ty)))
                    .collect();
                let values: Vec<String> = (0..variant.payload.len())
                    .map(|index| format!("_{index}"))
                    .collect();
                out.push_str(&format!(
                    "def {}({}) -> {}:\n    return {}({}, ({},), {order})\n\n",
                    name,
                    params.join(", "),
                    decl.name,
                    decl.name,
                    quote(&variant.name),
                    values.join(", ")
                ));
            }
        }

        out.push_str(&format!("def _{}_display(value: {}) -> str:\n", snake(&decl.name), decl.name));
        for variant in &decl.variants {
            out.push_str(&format!(
                "    if value.tag == {}:\n",
                quote(&variant.name)
            ));
            if variant.payload.is_empty() {
                out.push_str(&format!(
                    "        return {}\n",
                    quote(&format!("{}.{}", decl.name, variant.name))
                ));
            } else {
                let mut expression = quote(&format!("{}.{}(", decl.name, variant.name));
                for (index, _) in variant.payload.iter().enumerate() {
                    if index > 0 {
                        expression.push_str(" + \", \"");
                    }
                    expression.push_str(&format!(
                        " + lt.disp(value.values[{index}])"
                    ));
                }
                expression.push_str(" + \")\"");
                out.push_str(&format!("        return {}\n", expression));
            }
        }
        out.push_str("    raise AssertionError(\"unreachable\")\n");
        out
    }

    fn class_decl(&mut self, class: &IrClass) -> String {
        let mut out = String::new();
        out.push_str("@dataclass(frozen=True)\n");
        out.push_str(&format!("class {}:\n", class.name));

        if !class.fields.is_empty() {
            for field in &class.fields {
                let ty = self.type_ref(&field.ty);
                out.push_str(&format!("    {}: {}\n", member(&field.name), ty));
            }
            out.push('\n');
        } else {
            out.push_str("    pass\n\n");
        }

        for method in &class.methods {
            out.push_str(&self.method_decl(method));
            out.push('\n');
        }

        out.push_str(&format!("    def lt_cmp(self, other: \"{}\") -> int:\n", class.name));
        for field in &class.fields {
            let name = member(&field.name);
            out.push_str(&format!(
                "        step = lt.cmp(self.{name}, other.{name})\n        if step != 0:\n            return step\n"
            ));
        }
        out.push_str("        return 0\n\n");

        out.push_str("    def to_display(self) -> str:\n");
        if class.fields.is_empty() {
            out.push_str(&format!("        return {}\n", quote(&class.name)));
        } else {
            let mut expression = quote(&format!("{}(", class.name));
            for (index, field) in class.fields.iter().enumerate() {
                if index > 0 {
                    expression.push_str(" + \", \"");
                }
                expression.push_str(&format!(
                    " + {} + lt.disp(self.{})",
                    quote(&format!("{}: ", field.name)),
                    member(&field.name)
                ));
            }
            expression.push_str(" + \")\"");
            out.push_str(&format!("        return {}\n", expression));
        }

        out
    }

    fn method_decl(&mut self, method: &IrMethod) -> String {
        let mut params = Vec::new();
        if !method.is_static {
            params.push("self".to_string());
        }
        for param in &method.params {
            let ty = self.type_ref(&param.ty);
            params.push(format!("{}: {}", member(&param.name), ty));
        }
        let ret = self.type_ref(&method.ret);
        let mut out = String::new();
        if method.is_static {
            out.push_str("    @staticmethod\n");
        }
        out.push_str(&format!(
            "    def {}({}) -> {}:\n",
            member(&method.name),
            params.join(", "),
            ret
        ));
        let tail = if matches!(method.ret, Ty::Unit) {
            Tail::Plain
        } else {
            Tail::Return
        };
        let lines = self.block_lines(&method.body, 2, &tail);
        if lines.is_empty() {
            out.push_str("        pass\n");
        }
        for line in lines {
            out.push_str(&line);
            out.push('\n');
        }
        out
    }

    fn free_function(&mut self, method: &IrMethod, private: bool) -> String {
        let params: Vec<String> = method
            .params
            .iter()
            .map(|param| {
                let ty = self.type_ref(&param.ty);
                format!("{}: {}", member(&param.name), ty)
            })
            .collect();
        let ret = self.type_ref(&method.ret);
        let prefix = if private { "_" } else { "" };
        let mut out = format!(
            "def {}{}({}) -> {}:\n",
            prefix,
            snake(&method.name),
            params.join(", "),
            ret
        );
        let tail = if matches!(method.ret, Ty::Unit) {
            Tail::Plain
        } else {
            Tail::Return
        };
        let lines = self.block_lines(&method.body, 1, &tail);
        if lines.is_empty() {
            out.push_str("    pass\n");
        }
        for line in lines {
            out.push_str(&line);
            out.push('\n');
        }
        out
    }

    // ------------------------------------------------------------ statements

    fn block_lines(&mut self, block: &IrBlock, level: usize, tail: &Tail) -> Vec<String> {
        let mut lines = Vec::new();
        let count = block.stmts.len();
        for (index, stmt) in block.stmts.iter().enumerate() {
            let is_last = index + 1 == count;
            let stmt_tail = if is_last {
                tail.clone()
            } else {
                Tail::Plain
            };
            lines.extend(self.stmt(stmt, level, &stmt_tail));
        }
        lines
    }

    fn stmt(&mut self, stmt: &IrStmt, level: usize, tail: &Tail) -> Vec<String> {
        let pad = indent(level);
        match stmt {
            IrStmt::Let { name, ty, value, .. } => {
                let frag = self.expr(value, level);
                let declared = self.type_ref(ty);
                let mut lines = frag.prelude;
                lines.push(format!(
                    "{pad}{}: {} = {}",
                    member(name),
                    declared,
                    frag.code
                ));
                lines
            }
            IrStmt::Assign { name, value } => {
                let frag = self.expr(value, level);
                let mut lines = frag.prelude;
                lines.push(format!("{pad}{} = {}", member(name), frag.code));
                lines
            }
            IrStmt::Return(value) => {
                let mut lines = Vec::new();
                match value {
                    Some(value) => {
                        let frag = self.expr(value, level);
                        lines.extend(frag.prelude);
                        lines.push(format!("{pad}return {}", frag.code));
                    }
                    None => lines.push(format!("{pad}return")),
                }
                lines
            }
            IrStmt::For {
                var, iter, body, ..
            } => {
                let frag = self.expr(iter, level);
                let mut lines = frag.prelude;
                lines.push(format!("{pad}for {} in {}.items:", member(var), frag.code));
                lines.extend(self.indented_block(body, level + 1, &Tail::Plain));
                lines
            }
            IrStmt::While { cond, body } => {
                let frag = self.expr(cond, level);
                let mut lines = frag.prelude;
                lines.push(format!("{pad}while {}:", frag.code));
                lines.extend(self.indented_block(body, level + 1, &Tail::Plain));
                lines
            }
            IrStmt::Expr(expr) => match expr {
                IrExpr::If { .. } => self.if_stmt(expr, level, tail),
                IrExpr::Match { .. } => self.match_stmt(expr, level, tail),
                other => {
                    let frag = self.expr(other, level);
                    let mut lines = frag.prelude;
                    match tail {
                        Tail::Plain => lines.push(format!("{pad}{}", frag.code)),
                        Tail::Return => lines.push(format!("{pad}return {}", frag.code)),
                        Tail::Assign(target) => {
                            lines.push(format!("{pad}{target} = {}", frag.code))
                        }
                    }
                    lines
                }
            },
        }
    }

    /// Body lines for a compound statement, with `pass` when empty.
    fn indented_block(&mut self, block: &IrBlock, level: usize, tail: &Tail) -> Vec<String> {
        let lines = self.block_lines(block, level, tail);
        if lines.is_empty() {
            vec![format!("{}pass", indent(level))]
        } else {
            lines
        }
    }

    fn if_stmt(&mut self, expr: &IrExpr, level: usize, tail: &Tail) -> Vec<String> {
        let IrExpr::If {
            cond,
            then_block,
            else_branch,
            ..
        } = expr
        else {
            unreachable!("if_stmt expects `if`")
        };
        let pad = indent(level);
        let cond_frag = self.expr(cond, level);
        let mut lines = cond_frag.prelude;
        lines.push(format!("{pad}if {}:", cond_frag.code));
        lines.extend(self.indented_block(then_block, level + 1, tail));

        let mut current = else_branch;
        loop {
            match current {
                None => break,
                Some(IrElse::Block(block)) => {
                    lines.push(format!("{pad}else:"));
                    lines.extend(self.indented_block(block, level + 1, tail));
                    break;
                }
                Some(IrElse::If(nested)) => {
                    if let IrExpr::If {
                        cond,
                        then_block,
                        else_branch,
                        ..
                    } = nested.as_ref()
                    {
                        let cond_frag = self.expr(cond, level);
                        lines.extend(cond_frag.prelude);
                        lines.push(format!("{pad}elif {}:", cond_frag.code));
                        lines.extend(self.indented_block(then_block, level + 1, tail));
                        current = else_branch;
                    } else {
                        break;
                    }
                }
            }
        }
        lines
    }

    fn match_stmt(&mut self, expr: &IrExpr, level: usize, tail: &Tail) -> Vec<String> {
        let IrExpr::Match {
            scrutinee, arms, ..
        } = expr
        else {
            unreachable!("match_stmt expects `match`")
        };
        let pad = indent(level);
        let scrutinee_frag = self.expr(scrutinee, level);
        let binding = self.temp("match");
        let mut lines = scrutinee_frag.prelude;
        lines.push(format!("{pad}{binding} = {}", scrutinee_frag.code));

        let mut first = true;
        for arm in arms {
            match &arm.pattern {
                IrPattern::Variant { variant, bindings } => {
                    let keyword = if first { "if" } else { "elif" };
                    lines.push(format!(
                        "{pad}{keyword} {binding}.tag == {}:",
                        quote(variant)
                    ));
                    let body_level = level + 1;
                    let mut body = Vec::new();
                    for (index, (name, ty)) in bindings.iter().enumerate() {
                        let declared = self.type_ref(ty);
                        body.push(format!(
                            "{}{}: {} = {binding}.values[{index}]",
                            indent(body_level),
                            member(name),
                            declared
                        ));
                    }
                    body.extend(self.block_lines(&arm.body, body_level, tail));
                    if body.is_empty() {
                        body.push(format!("{}pass", indent(body_level)));
                    }
                    lines.extend(body);
                    first = false;
                }
                IrPattern::Binding { name, ty } => {
                    let declared = self.type_ref(ty);
                    lines.push(format!("{pad}else:"));
                    let body_level = level + 1;
                    let mut body = vec![format!(
                        "{}{}: {} = {binding}",
                        indent(body_level),
                        member(name),
                        declared
                    )];
                    body.extend(self.block_lines(&arm.body, body_level, tail));
                    lines.extend(body);
                    first = false;
                }
                IrPattern::Wildcard => {
                    lines.push(format!("{pad}else:"));
                    lines.extend(self.indented_block(&arm.body, level + 1, tail));
                    first = false;
                }
            }
        }

        if first {
            lines.push(format!("{pad}raise AssertionError(\"unreachable\")"));
        } else if !matches!(arms.last().map(|arm| &arm.pattern), Some(IrPattern::Binding { .. }) | Some(IrPattern::Wildcard)) {
            lines.push(format!("{pad}else:"));
            lines.push(format!("{}raise AssertionError(\"unreachable\")", indent(level + 1)));
        }

        lines
    }

    // ---------------------------------------------------------- expressions

    fn expr(&mut self, expr: &IrExpr, level: usize) -> Frag {
        match expr {
            IrExpr::Int(value) => Frag {
                prelude: Vec::new(),
                code: value.to_string(),
            },
            IrExpr::Float(value) => Frag {
                prelude: Vec::new(),
                code: format_float(*value),
            },
            IrExpr::Str(value) => Frag {
                prelude: Vec::new(),
                code: quote(value),
            },
            IrExpr::Bool(value) => Frag {
                prelude: Vec::new(),
                code: if *value { "True" } else { "False" }.to_string(),
            },
            IrExpr::Var(name) => Frag {
                prelude: Vec::new(),
                code: member(name),
            },
            IrExpr::SelfRef => Frag {
                prelude: Vec::new(),
                code: "self".to_string(),
            },
            IrExpr::List { items, .. } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = items
                    .iter()
                    .map(|item| {
                        let frag = self.expr(item, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let tuple = if rendered.len() == 1 {
                    format!("({},)", rendered[0])
                } else {
                    format!("({})", rendered.join(", "))
                };
                Frag {
                    prelude,
                    code: format!("lt.LList({tuple})"),
                }
            }
            IrExpr::EmptyCollection { ty } => {
                let code = match ty {
                    Ty::Map(_, _) => "lt.LMap.empty()".to_string(),
                    Ty::Set(_) => "lt.LSet.empty()".to_string(),
                    _ => "lt.LList(())".to_string(),
                };
                Frag {
                    prelude: Vec::new(),
                    code,
                }
            }
            IrExpr::Field { base, name, .. } => {
                let frag = self.expr(base, level);
                Frag {
                    prelude: frag.prelude,
                    code: format!("{}.{}", frag.code, member(name)),
                }
            }
            IrExpr::ClassNew {
                module,
                class,
                args,
                ..
            } => {
                let class_ref = self.class_ref(*module, class);
                let mut prelude = Vec::new();
                let fields: Vec<String> = args
                    .iter()
                    .map(|(name, value)| {
                        let frag = self.expr(value, level);
                        prelude.extend(frag.prelude);
                        format!("{}={}", member(name), frag.code)
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{class_ref}({})", fields.join(", ")),
                }
            }
            IrExpr::NewVariant {
                target, variant, args, ..
            } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let code = match target {
                    VariantRef::Option => {
                        if variant == "Some" {
                            format!("lt.Some({})", rendered.join(", "))
                        } else {
                            "lt.None_()".to_string()
                        }
                    }
                    VariantRef::Result => {
                        if variant == "Ok" {
                            format!("lt.Ok({})", rendered.join(", "))
                        } else {
                            format!("lt.Err({})", rendered.join(", "))
                        }
                    }
                    VariantRef::Enum { module, name } => {
                        let reference = self.variant_ref(*module, name, variant);
                        if rendered.is_empty() {
                            reference
                        } else {
                            format!("{reference}({})", rendered.join(", "))
                        }
                    }
                };
                Frag { prelude, code }
            }
            IrExpr::LocalCall { name, args, .. } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("_{}({})", member(name), rendered.join(", ")),
                }
            }
            IrExpr::StaticCall {
                module,
                class,
                method,
                args,
                ..
            } => {
                let class_ref = self.class_ref(*module, class);
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{class_ref}.{}({})", member(method), rendered.join(", ")),
                }
            }
            IrExpr::InstanceCall {
                receiver,
                method,
                args,
                ..
            } => {
                let recv = self.expr(receiver, level);
                let mut prelude = recv.prelude;
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: format!("{}.{}({})", recv.code, member(method), rendered.join(", ")),
                }
            }
            IrExpr::Builtin {
                kind,
                receiver,
                args,
                ..
            } => {
                let recv = self.expr(receiver, level);
                let mut prelude = recv.prelude;
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                Frag {
                    prelude,
                    code: self.builtin(*kind, &recv.code, &rendered),
                }
            }
            IrExpr::Math { name, args, .. } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                self.uses_math = true;
                let code = match name.as_str() {
                    "pi" => "math.pi".to_string(),
                    "pow" => format!("math.pow({})", rendered.join(", ")),
                    "abs" | "min" | "max" => format!("{}({})", name, rendered.join(", ")),
                    other => format!("math.{other}({})", rendered.join(", ")),
                };
                Frag { prelude, code }
            }
            IrExpr::Expect { name, args } => {
                let mut prelude = Vec::new();
                let rendered: Vec<String> = args
                    .iter()
                    .map(|arg| {
                        let frag = self.expr(arg, level);
                        prelude.extend(frag.prelude);
                        frag.code
                    })
                    .collect();
                let function = match name.as_str() {
                    "equal" => "expect_equal",
                    "not_equal" => "expect_not_equal",
                    "true" => "expect_true",
                    "false" => "expect_false",
                    other => other,
                };
                Frag {
                    prelude,
                    code: format!("lt.{function}({})", rendered.join(", ")),
                }
            }
            IrExpr::ToStr { value, .. } => {
                let frag = self.expr(value, level);
                Frag {
                    prelude: frag.prelude,
                    code: format!("lt.disp({})", frag.code),
                }
            }
            IrExpr::Template { parts, exprs } => {
                let mut prelude = Vec::new();
                let mut code = quote(parts.first().map(String::as_str).unwrap_or(""));
                for (index, inner) in exprs.iter().enumerate() {
                    let frag = self.expr(inner, level);
                    prelude.extend(frag.prelude);
                    code.push_str(&format!(" + lt.disp({})", frag.code));
                    if let Some(part) = parts.get(index + 1) {
                        if !part.is_empty() {
                            code.push_str(&format!(" + {}", quote(part)));
                        }
                    }
                }
                Frag { prelude, code }
            }
            IrExpr::Try { value, source_ty, .. } => {
                let frag = self.expr(value, level);
                let mut prelude = frag.prelude;
                let temp = self.temp("try");
                let pad = indent(level);
                let error_tag = match source_ty {
                    Ty::Option(_) => "none",
                    _ => "err",
                };
                prelude.push(format!("{pad}{temp} = {}", frag.code));
                prelude.push(format!(
                    "{pad}if {temp}.tag == {}:",
                    quote(error_tag)
                ));
                prelude.push(format!("{}return {temp}", indent(level + 1)));
                Frag {
                    prelude,
                    code: format!("{temp}.values[0]"),
                }
            }
            IrExpr::If { ty, .. } => {
                let target = self.temp("if");
                let pad = indent(level);
                let declared = self.type_ref(ty);
                let mut prelude = vec![format!("{pad}{target}: {declared} = None")];
                prelude.extend(self.if_stmt(expr, level, &Tail::Assign(target.clone())));
                Frag {
                    prelude,
                    code: target,
                }
            }
            IrExpr::Match { ty, .. } => {
                let target = self.temp("match");
                let pad = indent(level);
                let declared = self.type_ref(ty);
                let mut prelude = vec![format!("{pad}{target}: {declared} = None")];
                prelude.extend(self.match_stmt(expr, level, &Tail::Assign(target.clone())));
                Frag {
                    prelude,
                    code: target,
                }
            }
            IrExpr::Bin { op, lhs, rhs, ty } => {
                let left = self.expr(lhs, level);
                let right = self.expr(rhs, level);
                let mut prelude = left.prelude;
                prelude.extend(right.prelude);
                let code = self.binary(*op, &left.code, &right.code, ty);
                Frag { prelude, code }
            }
            IrExpr::Un { op, value, ty } => {
                let frag = self.expr(value, level);
                let code = match (op, ty) {
                    (UnOp::Not, _) => format!("(not ({}))", frag.code),
                    (UnOp::Neg, Ty::Int) => format!("lt.ineg({})", frag.code),
                    (UnOp::Neg, _) => format!("(-{})", frag.code),
                };
                Frag {
                    prelude: frag.prelude,
                    code,
                }
            }
            IrExpr::Lambda { params, body, .. } => {
                let rendered: Vec<String> = params
                    .iter()
                    .map(|param| member(&param.name))
                    .collect();
                match body {
                    IrLambdaBody::Expr(inner) => {
                        let frag = self.expr(inner, level);
                        if frag.prelude.is_empty() {
                            Frag {
                                prelude: Vec::new(),
                                code: format!("lambda {}: {}", rendered.join(", "), frag.code),
                            }
                        } else {
                            self.lambda_function(params, &[IrStmt::Expr((**inner).clone())], level)
                        }
                    }
                    IrLambdaBody::Block(block) => {
                        self.lambda_function(params, &block.stmts, level)
                    }
                }
            }
        }
    }

    fn lambda_function(
        &mut self,
        params: &[IrParam],
        stmts: &[IrStmt],
        level: usize,
    ) -> Frag {
        let name = self.temp("lambda");
        let pad = indent(level);
        let rendered: Vec<String> = params
            .iter()
            .map(|param| {
                let ty = self.type_ref(&param.ty);
                format!("{}: {}", member(&param.name), ty)
            })
            .collect();
        let mut prelude = vec![format!("{pad}def {name}({}) -> Any:", rendered.join(", "))];
        let block = IrBlock {
            stmts: stmts.to_vec(),
            ty: Ty::Unit,
        };
        let lines = self.block_lines(&block, level + 1, &Tail::Return);
        if lines.is_empty() {
            prelude.push(format!("{}pass", indent(level + 1)));
        }
        prelude.extend(lines);
        Frag {
            prelude,
            code: name,
        }
    }

    fn binary(&mut self, op: BinOp, left: &str, right: &str, ty: &Ty) -> String {
        match op {
            BinOp::Add | BinOp::Sub | BinOp::Mul | BinOp::Div | BinOp::Rem => {
                let symbol = match op {
                    BinOp::Add => "+",
                    BinOp::Sub => "-",
                    BinOp::Mul => "*",
                    BinOp::Div => "/",
                    _ => "%",
                };
                if matches!(ty, Ty::Int) {
                    let function = match op {
                        BinOp::Add => "iadd",
                        BinOp::Sub => "isub",
                        BinOp::Mul => "imul",
                        BinOp::Div => "idiv",
                        _ => "irem",
                    };
                    format!("lt.{function}({left}, {right})")
                } else if matches!(op, BinOp::Div) {
                    format!("lt.fdiv({left}, {right})")
                } else {
                    format!("({left} {symbol} {right})")
                }
            }
            BinOp::Eq => format!("lt.eq({left}, {right})"),
            BinOp::Ne => format!("(not lt.eq({left}, {right}))"),
            BinOp::Lt => format!("({left} < {right})"),
            BinOp::Le => format!("({left} <= {right})"),
            BinOp::Gt => format!("({left} > {right})"),
            BinOp::Ge => format!("({left} >= {right})"),
            BinOp::And => format!("({left} and {right})"),
            BinOp::Or => format!("({left} or {right})"),
        }
    }

    fn builtin(&mut self, kind: Builtin, recv: &str, args: &[String]) -> String {
        let call = |name: &str| format!("{recv}.{name}({})", args.join(", "));
        match kind {
            Builtin::StrLen => format!("lt.str_len({recv})"),
            Builtin::StrTrim => format!("{recv}.strip()"),
            Builtin::StrTrimIndent => format!("lt.str_trim_indent({recv})"),
            Builtin::StrLower => format!("{recv}.lower()"),
            Builtin::StrUpper => format!("{recv}.upper()"),
            Builtin::StrSplit => format!("lt.str_split({recv}, {})", args.join(", ")),
            Builtin::StrStartsWith => format!("{recv}.startswith({})", args.join(", ")),
            Builtin::StrEndsWith => format!("{recv}.endswith({})", args.join(", ")),
            Builtin::StrContains => format!("({} in {recv})", args.join(", ")),
            Builtin::StrReplace => format!("lt.str_replace({recv}, {})", args.join(", ")),
            Builtin::StrSlice => format!("lt.str_slice({recv}, {})", args.join(", ")),
            Builtin::StrChars => format!("lt.str_chars({recv})"),
            Builtin::StrParseInt => format!("lt.str_parse_int({recv})"),
            Builtin::StrParseFloat => format!("lt.str_parse_float({recv})"),
            Builtin::ListLen => format!("{recv}.len()"),
            Builtin::ListGet => call("get"),
            Builtin::ListPush => call("push"),
            Builtin::ListPop => format!("{recv}.pop()"),
            Builtin::ListMap => call("map"),
            Builtin::ListFilter => call("filter"),
            Builtin::ListFold => call("fold"),
            Builtin::ListAny => call("any"),
            Builtin::ListAll => call("all"),
            Builtin::ListSort => format!("{recv}.sort()"),
            Builtin::ListReverse => format!("{recv}.reverse()"),
            Builtin::ListConcat => call("concat"),
            Builtin::ListContains => call("contains"),
            Builtin::ListIndexOf => format!("{recv}.index_of({})", args.join(", ")),
            Builtin::ListJoin => call("join"),
            Builtin::SetLen => format!("{recv}.len()"),
            Builtin::SetInsert => call("insert"),
            Builtin::SetRemove => call("remove"),
            Builtin::SetContains => call("contains"),
            Builtin::SetUnion => call("union"),
            Builtin::SetIntersect => call("intersect"),
            Builtin::SetDifference => call("difference"),
            Builtin::MapLen => format!("{recv}.len()"),
            Builtin::MapGet => call("get"),
            Builtin::MapInsert => call("insert"),
            Builtin::MapRemove => call("remove"),
            Builtin::MapKeys => format!("{recv}.keys()"),
            Builtin::MapValues => format!("{recv}.values()"),
            Builtin::MapContainsKey => format!("{recv}.contains_key({})", args.join(", ")),
            Builtin::OptionIsSome => format!("lt.opt_is_some({recv})"),
            Builtin::OptionIsNone => format!("lt.opt_is_none({recv})"),
            Builtin::OptionUnwrap => format!("lt.opt_unwrap({recv})"),
            Builtin::OptionUnwrapOr => format!("lt.opt_unwrap_or({recv}, {})", args.join(", ")),
            Builtin::OptionMap => format!("lt.opt_map({recv}, {})", args.join(", ")),
            Builtin::OptionAndThen => format!("lt.opt_and_then({recv}, {})", args.join(", ")),
            Builtin::ResultIsOk => format!("lt.res_is_ok({recv})"),
            Builtin::ResultIsErr => format!("lt.res_is_err({recv})"),
            Builtin::ResultUnwrap => format!("lt.res_unwrap({recv})"),
            Builtin::ResultUnwrapOr => format!("lt.res_unwrap_or({recv}, {})", args.join(", ")),
            Builtin::ResultMap => format!("lt.res_map({recv}, {})", args.join(", ")),
            Builtin::ResultMapErr => format!("lt.res_map_err({recv}, {})", args.join(", ")),
            Builtin::ResultAndThen => format!("lt.res_and_then({recv}, {})", args.join(", ")),
        }
    }
}

fn format_float(value: f64) -> String {
    if value.is_nan() {
        return "float(\"nan\")".to_string();
    }
    if value.is_infinite() {
        return if value > 0.0 {
            "float(\"inf\")".to_string()
        } else {
            "float(\"-inf\")".to_string()
        };
    }
    if value.fract() == 0.0 {
        format!("{value:.1}")
    } else {
        format!("{value:?}")
    }
}
